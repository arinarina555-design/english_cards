"""
Простое Streamlit-приложение для ознакомления
Студенты могут запустить его и разобраться в основах работы
"""

import streamlit as st
import random

# Настройка страницы
st.set_page_config(
    page_title="Моё первое приложение",
    page_icon="🎯",
    layout="centered"
)

# Заголовок
st.title("🎯 Привет, это моё первое приложение на Streamlit!")

# Текст
st.markdown("""
### Что здесь можно сделать?

Это простое приложение для знакомства с возможностями Streamlit.
Попробуйте нажать на кнопки и ввести текст в поля!
""")

# Разделитель
st.divider()

# Кнопка
if st.button("Нажми меня!"):
    st.balloons()
    st.success("Ура! Кнопка работает!")

# Поле для ввода текста
name = st.text_input("Введите ваше имя:")
if name:
    st.write(f"Приятно познакомиться, **{name}**!")

# Слайдер
number = st.slider("Выберите число:", 1, 100, 50)
st.write(f"Вы выбрали число {number}")

# Случайное число
if st.button("Сгенерировать случайное число"):
    random_number = random.randint(1, 100)
    st.info(f"Случайное число: {random_number}")

# Информация
st.divider()
st.caption("Это приложение создано для знакомства с Streamlit. В курсовой работе вам предстоит создать гораздо более сложное приложение с базой данных!")